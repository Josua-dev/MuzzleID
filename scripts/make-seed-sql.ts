// Generates supabase/seed-demo.sql from the app's demo data so the live lookup has animals to find.
//   npx tsx scripts/make-seed-sql.ts
import fs from 'node:fs';
import { buildDemoDB } from '../src/data/demoData';
const d = buildDemoDB();
const q = (v: unknown) => (v === undefined || v === null ? 'null' : typeof v === 'boolean' ? String(v) : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const ins = (table: string, cols: string[], rows: Record<string, unknown>[]) =>
  rows.length ? `insert into public.${table} (${cols.join(', ')}) values\n${rows.map((r) => '  (' + cols.map((c) => q(r[c])).join(', ') + ')').join(',\n')}\non conflict do nothing;\n` : '';
const out = [
  '-- DEMO DATA ONLY (fake people, fake phone numbers). Generated by scripts/make-seed-sql.ts. Run after schema.sql.',
  ins('profiles', ['id', 'role', 'full_name', 'phone', 'email', 'active', 'is_demo', 'created_at'], d.users as never),
  ins('farmer_profiles', ['user_id', 'farm_name', 'region'], d.farmerProfiles as never),
  ins('animals', ['id', 'muzzle_id', 'owner_id', 'ear_tag', 'name', 'breed', 'sex', 'colour', 'birth_date', 'region', 'farm', 'status', 'health_status', 'photo_url', 'is_demo', 'created_at', 'updated_at'], d.animals as never),
  ins('ownership_records', ['id', 'animal_id', 'owner_id', 'owner_name', 'owner_phone', 'farm', 'region', 'start_date', 'end_date'], d.ownership as never),
  ins('theft_reports', ['id', 'animal_id', 'type', 'reported_at', 'last_seen_date', 'last_seen_location', 'description', 'status', 'reported_by_id'], (d.theftReports as any[]).map((t) => ({ ...t, reported_by_id: t.reported_by_id ?? t.reported_by ?? 'demo' })) as never),
].join('\n');
fs.writeFileSync('supabase/seed-demo.sql', out);
console.log(`wrote supabase/seed-demo.sql: ${d.users.length} users, ${d.animals.length} animals, ${d.theftReports.length} reports`);
